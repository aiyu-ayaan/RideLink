"""Single source of truth for the RideLink "Closed loop" mark. Run to regenerate every SVG and Android vector.

Construction (on a 256 grid): ring centred (128,128), centreline radius 88, weight 40, round ends.
The opening is centred on -45 deg (upper right); each end sits 33 deg from it so the spark (a dot of the
ring's weight, on the ring's own path) leaves an even 10-unit air gap to both ends.
"""
import math, os

R, W, GAP, SPARK = 88.0, 40.0, -45.0, 20.0
HALF = math.degrees(2 * math.asin((SPARK + W / 2 + 10) / 2 / R))  # = 33.0 deg

RED, AMBER, INK, WHITE = "#B3261E", "#FFB82E", "#1C1B1F", "#FFFFFF"
HERE = os.path.dirname(os.path.abspath(__file__))


def pt(cx, cy, r, a):
    a = math.radians(a)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def P(p):
    return f"{f(p[0])} {f(p[1])}"


def geometry(cx=128.0, cy=128.0, s=1.0):
    """Ring outline (filled, round caps), ring centreline, spark centre and radius, scaled by s around (cx,cy)."""
    r, h = R * s, W / 2 * s
    a0, a1 = GAP + HALF, GAP - HALF + 360   # clockwise from just after the opening round to just before it
    ro, ri = r + h, r - h
    outline = (f"M{P(pt(cx, cy, ro, a0))} A{f(ro)} {f(ro)} 0 1 1 {P(pt(cx, cy, ro, a1))} "
               f"A{f(h)} {f(h)} 0 0 1 {P(pt(cx, cy, ri, a1))} "
               f"A{f(ri)} {f(ri)} 0 1 0 {P(pt(cx, cy, ri, a0))} "
               f"A{f(h)} {f(h)} 0 0 1 {P(pt(cx, cy, ro, a0))} Z")
    centreline = f"M{P(pt(cx, cy, r, a0))} A{f(r)} {f(r)} 0 1 1 {P(pt(cx, cy, r, a1))}"
    spark = pt(cx, cy, r, GAP)
    return outline, centreline, spark, SPARK * s, W * s


def circle_path(c, r):
    return f"M{f(c[0] - r)} {f(c[1])} A{f(r)} {f(r)} 0 1 0 {f(c[0] + r)} {f(c[1])} A{f(r)} {f(r)} 0 1 0 {f(c[0] - r)} {f(c[1])} Z"


def svg(ring, spark, bg=None, title="RideLink logo", rx=0, s=1.0):
    o, _, sc, sr, _ = geometry(s=s)
    back = f'<rect width="256" height="256" rx="{rx}" fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256" role="img">'
            f'<title>{title}</title>{back}<path id="ring" fill="{ring}" d="{o}"/>'
            f'<circle id="spark" cx="{f(sc[0])}" cy="{f(sc[1])}" r="{f(sr)}" fill="{spark}"/></svg>\n')


def write(path, text):
    with open(path, "w") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(path, HERE))


ANDROID = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by development/brand/logo_geometry.py; edit the script, not this file. -->\n'


def vector(size_dp, viewport, cx, cy, s, ring, spark):
    o, _, sc, sr, _ = geometry(cx, cy, s)
    return (ANDROID + f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
            f'    <path android:fillColor="{ring}" android:pathData="{o}" />\n'
            f'    <path android:fillColor="{spark}" android:pathData="{circle_path(sc, sr)}" />\n'
            f'</vector>\n')


def splash_avd():
    """Android 12+ splash icon (240 dp, content inside the 160 dp circle), animated in 1000 ms:
    0-600   ring draws clockwise from its start (trimPathEnd 0 to 1) while the whole mark swings from -110 deg;
    420-720 spark pops in on the ring's path with an overshoot;
    640-1000 a ripple leaves the spark and fades: connected.
    The drawable's own values are the final frame, so devices without animation show the finished logo."""
    cx = cy = 120.0
    s = 150.0 / ((R + W / 2) * 2)              # outer diameter 150 of 240
    _, line, sc, sr, w = geometry(cx, cy, s)
    def anim(prop, a, b, start, dur, interp, kind="floatType"):
        return (f'            <objectAnimator android:propertyName="{prop}" android:valueFrom="{a}" android:valueTo="{b}"\n'
                f'                android:valueType="{kind}" android:startOffset="{start}" android:duration="{dur}"\n'
                f'                android:interpolator="{interp}" />\n')
    def target(name, animators):
        return (f'    <target android:name="{name}">\n        <aapt:attr name="android:animation">\n'
                f'            <set>\n{"".join(animators)}            </set>\n        </aapt:attr>\n    </target>\n')
    ease = "@android:interpolator/fast_out_slow_in"
    out_ease = "@android:interpolator/linear_out_slow_in"
    pop = "@android:anim/overshoot_interpolator"
    drawable = (f'        <vector android:width="240dp" android:height="240dp" android:viewportWidth="240" android:viewportHeight="240">\n'
                f'            <group android:name="mark" android:pivotX="{f(cx)}" android:pivotY="{f(cy)}">\n'
                # Ring takes the app's primary role (values/, values-night/, values-v31/ splash_ring) to match the theme.
                f'                <path android:name="ring" android:strokeColor="@color/splash_ring" android:strokeWidth="{f(w)}"\n'
                f'                    android:strokeLineCap="round" android:trimPathEnd="1" android:pathData="{line}" />\n'
                f'                <group android:name="spark" android:pivotX="{f(sc[0])}" android:pivotY="{f(sc[1])}">\n'
                f'                    <path android:fillColor="{AMBER}" android:pathData="{circle_path(sc, sr)}" />\n'
                f'                </group>\n'
                f'                <group android:name="pulse" android:pivotX="{f(sc[0])}" android:pivotY="{f(sc[1])}">\n'
                f'                    <path android:name="pulseRing" android:strokeColor="{AMBER}" android:strokeWidth="{f(w * 0.25)}"\n'
                f'                        android:strokeAlpha="0" android:pathData="{circle_path(sc, sr)}" />\n'
                f'                </group>\n'
                f'            </group>\n        </vector>\n')
    return (ANDROID + '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt">\n'
            '    <aapt:attr name="android:drawable">\n' + drawable + '    </aapt:attr>\n'
            + target("mark", [anim("rotation", -110, 0, 0, 640, ease)])
            + target("ring", [anim("trimPathEnd", 0, 1, 0, 600, ease)])
            # Hold the spark at 0 from the first frame: an animator only applies valueFrom once its offset is reached.
            + target("spark", [anim("scaleX", 0, 0, 0, 1, ease), anim("scaleY", 0, 0, 0, 1, ease),
                               anim("scaleX", 0, 1, 420, 300, pop), anim("scaleY", 0, 1, 420, 300, pop)])
            + target("pulse", [anim("scaleX", 1, 2.6, 640, 360, out_ease), anim("scaleY", 1, 2.6, 640, 360, out_ease)])
            + target("pulseRing", [anim("strokeAlpha", 0.9, 0, 640, 360, out_ease)])
            + '</animated-vector>\n')


if __name__ == "__main__":
    root = os.path.normpath(os.path.join(HERE, "..", ".."))
    app_res = os.path.join(root, "app", "src", "main", "res")
    ui_res = os.path.join(root, "ui", "src", "main", "res")
    # Adaptive icon: 108 dp canvas, the mark (outer diameter 58) inside the 66 dp safe circle.
    s_icon = 58.0 / ((R + W / 2) * 2)
    # Ring in the app's tonal colour (values*/splash_colors.xml icon_ring), on icon_background, to match the theme.
    write(os.path.join(app_res, "drawable", "ic_launcher_foreground.xml"), vector(108, 108, 54, 54, s_icon, "@color/icon_ring", AMBER))
    write(os.path.join(app_res, "drawable", "ic_launcher_monochrome.xml"), vector(108, 108, 54, 54, s_icon, INK, INK))
    # Notification small icon: white silhouette, 24 dp with 1 dp padding.
    write(os.path.join(ui_res, "drawable", "ic_ridelink.xml"), vector(24, 24, 12, 12, 22.0 / ((R + W / 2) * 2), WHITE, WHITE))
    write(os.path.join(app_res, "drawable", "splash_logo_animated.xml"), splash_avd())

    out = os.path.join(HERE, "final")
    write(os.path.join(out, "ridelink-symbol-color.svg"), svg(RED, INK, title="RideLink logo, colour on light"))
    write(os.path.join(out, "ridelink-symbol-on-red.svg"), svg(WHITE, AMBER, bg=RED, title="RideLink logo on red"))
    write(os.path.join(out, "ridelink-symbol-black.svg"), svg(INK, INK, title="RideLink logo, one colour"))
    write(os.path.join(out, "ridelink-symbol-white.svg"), svg(WHITE, WHITE, bg=INK, title="RideLink logo, reversed"))
    write(os.path.join(out, "ridelink-app-icon.svg"), svg(WHITE, AMBER, bg=RED, rx=56, s=0.7, title="RideLink app icon"))
